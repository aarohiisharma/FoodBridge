-- FoodBridge PostgreSQL schema.
-- Safe for a fresh database: this script does not drop or overwrite objects.
BEGIN;

CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(120) NOT NULL CHECK (btrim(name) <> ''),
    email           VARCHAR(320) NOT NULL,
    password_hash   TEXT NOT NULL CHECK (password_hash <> ''),
    phone           VARCHAR(32),
    role            VARCHAR(16) NOT NULL
                    CHECK (role IN ('DONOR', 'NGO', 'VOLUNTEER', 'ADMIN')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX users_email_lower_unique
    ON users (lower(email));

CREATE TABLE ngo_profiles (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL UNIQUE
                        REFERENCES users(id) ON DELETE CASCADE,
    organization_name   VARCHAR(200) NOT NULL
                        CHECK (btrim(organization_name) <> ''),
    registration_number VARCHAR(100) UNIQUE,
    verification_status VARCHAR(16) NOT NULL DEFAULT 'PENDING'
                        CHECK (verification_status IN ('PENDING', 'VERIFIED', 'REJECTED')),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE donations (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donor_id         BIGINT NOT NULL
                     REFERENCES users(id) ON DELETE RESTRICT,
    food_name        VARCHAR(200) NOT NULL CHECK (btrim(food_name) <> ''),
    food_type        VARCHAR(80) NOT NULL CHECK (btrim(food_type) <> ''),
    quantity         NUMERIC(12, 3) NOT NULL CHECK (quantity > 0),
    quantity_unit    VARCHAR(24) NOT NULL CHECK (btrim(quantity_unit) <> ''),
    preparation_time TIMESTAMPTZ NOT NULL,
    expiry_time      TIMESTAMPTZ NOT NULL,
    description      TEXT,
    pickup_location  TEXT NOT NULL CHECK (btrim(pickup_location) <> ''),
    image_url        TEXT,
    status           VARCHAR(16) NOT NULL DEFAULT 'AVAILABLE'
                     CHECK (status IN ('AVAILABLE', 'CLAIMED', 'COMPLETED', 'CANCELLED', 'EXPIRED')),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT donations_expiry_after_preparation
        CHECK (expiry_time > preparation_time)
);

CREATE TABLE pickup_requests (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donation_id  BIGINT NOT NULL
                 REFERENCES donations(id) ON DELETE RESTRICT,
    ngo_id       BIGINT NOT NULL
                 REFERENCES ngo_profiles(user_id) ON DELETE RESTRICT,
    volunteer_id BIGINT
                 REFERENCES users(id) ON DELETE SET NULL,
    status       VARCHAR(16) NOT NULL DEFAULT 'PENDING'
                 CHECK (status IN (
                     'PENDING', 'APPROVED', 'REJECTED', 'ASSIGNED', 'ACCEPTED',
                     'IN_TRANSIT', 'COLLECTED', 'DELIVERED', 'COMPLETED', 'CANCELLED'
                 )),
    notes        TEXT,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE pickup_status_history (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pickup_request_id   BIGINT NOT NULL
                        REFERENCES pickup_requests(id) ON DELETE CASCADE,
    previous_status     VARCHAR(16),
    status              VARCHAR(16) NOT NULL
                        CHECK (status IN (
                            'PENDING', 'APPROVED', 'REJECTED', 'ASSIGNED', 'ACCEPTED',
                            'IN_TRANSIT', 'COLLECTED', 'DELIVERED', 'COMPLETED', 'CANCELLED'
                        )),
    changed_by_user_id  BIGINT
                        REFERENCES users(id) ON DELETE SET NULL,
    changed_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    note                TEXT,
    CONSTRAINT pickup_history_previous_status_valid
        CHECK (previous_status IS NULL OR previous_status IN (
            'PENDING', 'APPROVED', 'REJECTED', 'ASSIGNED', 'ACCEPTED',
            'IN_TRANSIT', 'COLLECTED', 'DELIVERED', 'COMPLETED', 'CANCELLED'
        )),
    CONSTRAINT pickup_history_status_changed
        CHECK (previous_status IS NULL OR previous_status <> status)
);

CREATE TABLE notifications (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL
                        REFERENCES users(id) ON DELETE CASCADE,
    type                VARCHAR(40) NOT NULL,
    message             TEXT NOT NULL CHECK (btrim(message) <> ''),
    pickup_request_id   BIGINT
                        REFERENCES pickup_requests(id) ON DELETE SET NULL,
    related_user_id     BIGINT
                        REFERENCES users(id) ON DELETE SET NULL,
    is_read             BOOLEAN NOT NULL DEFAULT FALSE,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT notifications_one_related_entity
        CHECK (pickup_request_id IS NULL OR related_user_id IS NULL)
);

CREATE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

CREATE TRIGGER users_set_updated_at
    BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER ngo_profiles_set_updated_at
    BEFORE UPDATE ON ngo_profiles
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER donations_set_updated_at
    BEFORE UPDATE ON donations
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER pickup_requests_set_updated_at
    BEFORE UPDATE ON pickup_requests
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE INDEX donations_donor_created_idx
    ON donations (donor_id, created_at DESC);

CREATE INDEX donations_available_expiry_idx
    ON donations (expiry_time, created_at DESC)
    WHERE status = 'AVAILABLE';

CREATE INDEX pickup_requests_ngo_requested_idx
    ON pickup_requests (ngo_id, requested_at DESC);

CREATE INDEX pickup_requests_volunteer_updated_idx
    ON pickup_requests (volunteer_id, updated_at DESC)
    WHERE volunteer_id IS NOT NULL;

CREATE INDEX pickup_requests_donation_requested_idx
    ON pickup_requests (donation_id, requested_at DESC);

CREATE UNIQUE INDEX pickup_requests_one_pending_per_ngo_idx
    ON pickup_requests (donation_id, ngo_id)
    WHERE status = 'PENDING';

-- APPROVED reserves the donation; subsequent active states keep that reservation.
CREATE UNIQUE INDEX pickup_requests_one_active_per_donation_idx
    ON pickup_requests (donation_id)
    WHERE status IN ('APPROVED', 'ASSIGNED', 'ACCEPTED', 'IN_TRANSIT', 'COLLECTED');

CREATE INDEX pickup_history_request_changed_idx
    ON pickup_status_history (pickup_request_id, changed_at DESC);

CREATE INDEX notifications_user_created_idx
    ON notifications (user_id, created_at DESC);

COMMIT;
